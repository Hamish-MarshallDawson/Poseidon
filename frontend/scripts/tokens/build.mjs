// Builds src/tokens/tokens.css and src/tokens/tokens.json from scripts/tokens/source.json (the one source of truth).
// Run: npm run tokens. Self-check: node scripts/tokens/build.mjs --check (fails if the outputs are stale).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const src = JSON.parse(readFileSync(here('./source.json'), 'utf8'))
const { themes, signalSets, textSizes } = src
const v = (name) => `--dvm-${name.replaceAll('/', '-')}`
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'))

// 'hex@NN' -> #rrggbbaa; MapLibre and CSS both take 8-digit hex, so readToken() returns something paintable.
function colour(value) {
  if (typeof value !== 'string' || !value.includes('@')) return String(value)
  const [hex, pct] = value.split('@')
  if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`bad colour ${value}`)
  return hex.toLowerCase() + Math.round((Number(pct) / 100) * 255).toString(16).padStart(2, '0')
}

// Resolved signal colour for one set and theme column, including the derived ghost colours.
function signal(name, set, t) {
  if (src.signals[name]) return colour(src.signals[name][set][t])
  const [base, pct] = src.derivedSignals[name].split('@')
  return colour(`${src.signals[base][set][t]}@${pct}`)
}
const signalNames = [...Object.keys(src.signals), ...entries(src.derivedSignals).map(([k]) => k)]
const setKey = { standard: 'std', cvd: 'cvd' }

const json = { modes: { theme: themes, signals: signalSets, text: textSizes }, theme: {}, signals: {}, text: {}, constants: {} }
const css = []
const block = (selector, lines) => css.push(`${selector} {\n${lines.map((l) => `  ${l};`).join('\n')}\n}`)

block(':root', entries(src.constants).map(([k, val]) => {
  json.constants[v(k)] = val
  return `${v(k)}: ${val}`
}))

// Theme: every role per theme, plus the hidden signal-std-* / signal-cvd-* colours the signals alias into.
themes.forEach((theme, t) => {
  const lines = []
  for (const [k, cols] of [...entries(src.theme), ...entries(src.extraTheme)]) {
    lines.push(`${v(k)}: ${colour(cols[t])}`)
    ;(json.theme[v(k)] ??= {})[theme] = colour(cols[t])
  }
  for (const set of signalSets) for (const k of signalNames) {
    lines.push(`${v(`signal-${setKey[set]}/${k}`)}: ${signal(k, set, t)}`)
    ;((json.signals[v(k)] ??= {})[set] ??= {})[theme] = signal(k, set, t)
  }
  block(t === 0 ? `:root, [data-theme="${theme}"]` : `[data-theme="${theme}"]`, lines)
})

// Signals and aliases resolve on every element that sets a mode, so a nested [data-theme] scope gets its own colours.
// A nested scope should set data-theme and data-signals together.
const aliasLines = entries(src.aliases).map(([k, target]) => {
  json.constants[v(k)] = `var(${v(target)})`
  return `${v(k)}: var(${v(target)})`
})
for (const set of signalSets) {
  const lines = signalNames.map((k) => `${v(k)}: var(${v(`signal-${setKey[set]}/${k}`)})`)
  block(set === 'standard' ? ':root, [data-theme], [data-signals]' : `[data-signals="${set}"]`,
    set === 'standard' ? [...lines, ...aliasLines] : lines)
}

textSizes.forEach((size, i) => {
  const lines = []
  for (const [role, steps] of entries(src.text)) {
    const [s, l] = steps[i]
    lines.push(`${v(`size/${role}`)}: ${s}px`, `${v(`line/${role}`)}: ${l}px`)
    ;(json.text[v(`size/${role}`)] ??= {})[size] = `${s}px`
    ;(json.text[v(`line/${role}`)] ??= {})[size] = `${l}px`
  }
  block(i === 0 ? `:root, [data-text="${size}"]` : `[data-text="${size}"]`, lines)
})

const header = '/* Generated by scripts/tokens/build.mjs from scripts/tokens/source.json. Do not edit; run npm run tokens. */\n'
const out = { '../../src/tokens/tokens.css': header + css.join('\n') + '\n', '../../src/tokens/tokens.json': JSON.stringify(json, null, 2) + '\n' }

// Self-check: every theme and signal row has a value for every mode.
for (const [k, cols] of entries(src.theme)) if (cols.length !== themes.length) throw new Error(`${k}: ${cols.length} columns`)
for (const k of signalNames) for (const set of signalSets) for (let t = 0; t < themes.length; t++) {
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/.test(signal(k, set, t))) throw new Error(`${k} ${set} ${themes[t]}`)
}

if (process.argv.includes('--check')) {
  const stale = Object.entries(out).filter(([p, text]) => readFileSync(here(p), 'utf8').replaceAll('\r\n', '\n') !== text)
  if (stale.length) { console.error(`stale: ${stale.map(([p]) => p).join(', ')}; run npm run tokens`); process.exit(1) }
  console.log('tokens up to date')
} else {
  for (const [p, text] of Object.entries(out)) writeFileSync(here(p), text)
  console.log(`wrote tokens.css (${out['../../src/tokens/tokens.css'].length} B) and tokens.json`)
}
